# shellcheck shell=zsh
# ShellSpec tests for the hand-rolled try-rs shell integration.
#
# The module must keep $XDG_CONFIG_HOME/try-rs/try-rs.zsh in place (its
# existence is what stops try-rs from prompting to edit ~/.zshrc) and must
# regenerate it only when the resolved binary path changes.

Describe 'try-rs shell integration (completion.zsh)'
  MODULE="zsh-setup-scripts/try-rs/completion.zsh"

  setup() {
    REPO_ROOT="$PWD"
    TEST_DIR="${$(mktemp -d):A}"  # :A, as the module resolves /var -> /private/var
    export XDG_CONFIG_HOME="${TEST_DIR}/xdg"
    unset TRY_CONFIG_DIR
    SCRIPT="${XDG_CONFIG_HOME}/try-rs/try-rs.zsh"
    CALLS="${TEST_DIR}/calls"

    # Stub binary: count calls, emit a wrapper function and a compdef line.
    mkdir -p "${TEST_DIR}/v1" "${TEST_DIR}/v2"
    for v in v1 v2; do
      cat > "${TEST_DIR}/${v}/try-rs" <<EOF
#!/bin/sh
echo call >> "${CALLS}"
echo 'try-rs() { echo stub-${v}; }'
echo 'compdef _try_rs_complete try-rs'
echo 'tries_path=\$(echo x | sed "s|~|\$HOME|")'
EOF
      chmod +x "${TEST_DIR}/${v}/try-rs"
    done

    ORIG_PATH="$PATH"
    use_binary v1
  }

  cleanup() {
    export PATH="$ORIG_PATH"
    rehash
    unfunction try-rs 2>/dev/null
    rm -rf "$TEST_DIR"
  }

  BeforeEach 'setup'
  AfterEach 'cleanup'

  use_binary() {
    export PATH="${TEST_DIR}/$1:${ORIG_PATH}"
    rehash
  }

  log_success() { :; }
  log_error() { echo "ERROR: $*" >&2; }
  log_skip() { :; }
  compdef() { echo "compdef $*" >> "${TEST_DIR}/compdef"; }

  load_module() { source "${REPO_ROOT}/${MODULE}"; }
  call_count() { wc -l < "$CALLS" | tr -d ' '; }

  It 'writes the integration file where try-rs looks for it'
    When call load_module
    The path "$SCRIPT" should be file
    The line 1 of contents of file "$SCRIPT" should eq "# generated by dotfiles from ${TEST_DIR}/v1/try-rs"
  End

  It 'defines the wrapper function and registers completion'
    load_module
    When call try-rs
    The output should eq "stub-v1"
    The contents of file "${TEST_DIR}/compdef" should eq "compdef _try_rs_complete try-rs"
  End

  It 'does not run the binary again when the file is current'
    load_module
    load_module
    When call call_count
    The output should eq "1"
  End

  It 'regenerates the file when the binary path changes'
    load_module
    use_binary v2
    load_module
    When call try-rs
    The output should eq "stub-v2"
    The line 1 of contents of file "$SCRIPT" should eq "# generated by dotfiles from ${TEST_DIR}/v2/try-rs"
  End

  It 'patches the upstream ~ expansion to cover every comma-separated path'
    When call load_module
    The contents of file "$SCRIPT" should include 'sed "s|~|$HOME|g"'
  End

  It 'leaves no temp file behind'
    When call load_module
    The path "${SCRIPT}.tmp" should not be exist
  End
End
